def render(spec, step=""):
    source = (ROOT / "python" / spec["module"]).read_text()
    if "$$" in source:
        raise ValueError(f"{spec['module']} contains $$, which would end the SQL body")
    packages = ", ".join(f"'{p}'" for p in spec["packages"])
    intro = "\n".join(f"-- {line}".rstrip() for line in spec["intro"].splitlines())
    parts = [
        f"-- GENERATED by python/build_sql.py from python/{spec['module']}. Do not edit.\n"
        f"{intro}\n"
        "--\n"
        "-- Run in your student schema (USE SCHEMA student_your_name;).\n"
        "-- These are caller's rights procedures: they read and write tables in the\n"
        "-- schema that is current when you CALL them.\n"
        "-- Session context (role, database, warehouse, schema) and shared values live in\n"
        "-- sql/runbook_config.sql. Run it first when running this file by hand."
    ]
    # Runbook DEFINE section, so the notebook can re-create these procedures when they change.
    handlers = ",".join(handler for _, handler in spec["procedures"])
    parts.append(f"-- @runbook:begin {step}.define role=DEFINE cost=none writes={handlers} "
                 f"purpose=Create {handlers.replace(',', ', ')}")
    for signature in spec.get("drop_first", []):
        parts.append(f"DROP PROCEDURE IF EXISTS {signature};")
    for signature, handler in spec["procedures"]:
        network = (
            f"  EXTERNAL_ACCESS_INTEGRATIONS = ({INTEGRATION})\n"
            "  SECRETS = ('dataexpert_api_key' = dataexpert_api_key)\n"
            if spec["network"] else ""
        )
        parts.append(
            f"CREATE OR REPLACE PROCEDURE {signature}\n"
            "  RETURNS VARIANT\n"
            "  LANGUAGE PYTHON\n"
            "  RUNTIME_VERSION = '3.12'\n"
            f"  PACKAGES = ({packages})\n"
            f"  HANDLER = '{handler}'\n"
            f"{network}"
            "  EXECUTE AS CALLER\n"
            f"AS\n$$\n{source.rstrip()}\n$$;"
        )
    parts.append(f"-- @runbook:end {step}.define")
    return "\n\n".join(parts) + "\n"


def main():
    for name, spec in PROCEDURES.items():
        path = ROOT / "sql" / name
        path.write_text(render(spec, step=name.split("_", 1)[0]))
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
